"""Serve the per-part repos over git's smart HTTP protocol.

`git http-backend` IS the smart HTTP server — it speaks the whole protocol
(v0/v1/v2, ref advertisement, upload-pack negotiation, sideband) as a CGI
program. Reimplementing that would be a mistake, so this module is only two
things: a CGI bridge, and the freshness hook that regenerates a part's repo
before its refs are advertised.

stdlib only, on purpose: the deployable is `python:3-slim` + git, no pip.

Routes
  GET  /                        plain-text index of what's servable
  GET  /healthz                 liveness + cache summary (JSON)
  GET  /api/parts               every item with a vault folder (JSON)
  GET  /api/parts/<NUMBER>      resolution + cache state for one part (JSON)
  POST /api/parts/<NUMBER>/refresh   force a rebuild (JSON)
  ANY  /git/<NUMBER>.git/...    git smart HTTP  <- `git clone` and `git push`

The read path is anonymous (private network posture). The WRITE path is not: every
receive-pack request — the ref advertisement as well as the pack POST — must carry
a bearer token that maps to a plm actor, and the resolved actor is handed to the
hooks in the environment. With PLMGIT_ALLOW_PUSH=0 (the default) receive-pack is
refused here AND disabled in every generated repo. See plm_git/push.py.

DIRECT-SERVE MODE (git-first POC, the design docs §E). With PLMGIT_DIRECT_ROOT set
to a directory of bare repos, none of the above happens: there is no vault, no
mirror, no extraction and no freshness hook, because the repos are the record
(generated by plm/split.py) rather than a projection of a monorepo. The CGI
bridge — the part that was always right — is reused unchanged, which is the
point: the transport did not have to change to make plm git-first.

Direct mode was read-only in stage 1. With PLMGIT_GITFIRST_ALLOW_PUSH=1 it now
also accepts a push: `refs/heads/draft/<topic>` and `refs/for/main`, validated
by plm/gitvalidate.py in git's quarantine and indexed by plm/gitindex.py. The
pushed commit is KEPT — plm does not re-author it — which is what makes the
sentence "a pushed commit IS the revision" literally true. See
plm_git/gitfirst.py.
"""
