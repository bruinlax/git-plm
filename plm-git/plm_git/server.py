_locks: dict[str, threading.Lock] = {}
_locks_guard = threading.Lock()


def _lock(number: str) -> threading.Lock:
    with _locks_guard:
        return _locks.setdefault(number, threading.Lock())


def ensure_fresh(number: str, force: bool = False) -> dict:
    """Resolve the number and make sure its bare repo matches the vault.

    THE auto-refresh trigger. It runs on the ref-advertisement request, which is
    the first thing every `git clone` / `git fetch` does — so a clone always
    gets current bytes and nobody ever runs a build step. Cost per clone is one
    vault fetch (itself rate-limited inside ensure_mirror) plus one rev-list;
    when nothing in the vault moved it is zero git calls.

    Serialised per part so two concurrent clones of the same number can't race
    the rebuild.
    """
    item = resolve(number)  # raises NotFound -> 404
    with _lock(item.number):
        return extract.build(item, force=force)


def list_parts() -> list[dict]:
    """Everything plm has a vault folder for, annotated with cache state."""
    import urllib.request
    out = []
    try:
        with urllib.request.urlopen(f"{config.PLM_URL}/api/items", timeout=8) as r:
            items = json.load(r)
    except Exception:
        items = []
    for it in items:
        if not it.get("folder"):
            continue
        st = extract.read_stamp(it["number"])
        out.append({
            "number": it["number"], "name": it.get("name", ""),
            "kind": it.get("kind", ""), "folder": it["folder"],
            "clone_url": f"/git/{it['number']}.git",
            "cached": bool(st), "commits": st.get("commits"),
            "generated_at": st.get("generated_at"),
        })
    return out


#: ⛔ M1 — HOW A REQUEST IS RECOGNISED AS A PUSH. **Confirmed live** in the
#: review: `?service=git-receive%2Dpack` walked straight past the door, because
#: this was `"receive-pack" in query` against the RAW query string while
#: `git http-backend` URL-decodes it before dispatching. One character of
#: encoding and the ref advertisement — which the module's own comment says is
#: authenticated precisely so a private part's refs are not shown to anyone who
#: asks to push — answered 200.
#:
#: So: decode with `parse_qs`, and FAIL CLOSED. Anything whose decoded
#: `service` is not one of the two git services, or whose path is not one of the
#: handful of smart-HTTP endpoints, is treated as a write.
_READ_SERVICES = ("git-upload-pack", "git-upload-archive")
_WRITE_SERVICES = ("git-receive-pack",)


def is_push(path_info: str, query: str) -> bool:
    """Is this request part of a PUSH? Decided once, for both doors.

    True when the path ends `/git-receive-pack` (the pack POST — http-backend
    does NOT decode PATH_INFO, so a literal match is right here), or when the
    DECODED `service` parameter asks for receive-pack, or when a `service=` was
    given that git does not recognise at all. The last clause is the fail-closed
    one: an unrecognised service is refused as a write rather than waved through
    as a read.
    """
    if path_info.endswith("/git-receive-pack"):
        return True
    try:
        params = urllib.parse.parse_qs(query or "", keep_blank_values=True)
    except Exception:                                       # noqa: BLE001
        return True
    services = [s.strip() for s in params.get("service", []) if s is not None]
    if not services:
        return False
    for svc in services:
        if svc in _WRITE_SERVICES:
            return True
        if svc not in _READ_SERVICES:
            return True            # unrecognised -> the strict answer
    return False


class Handler(BaseHTTPRequestHandler):
    server_version = "plm-git/0.1"
    protocol_version = "HTTP/1.1"

    # ---- helpers ---------------------------------------------------------
    def _json(self, obj, code: int = 200) -> None:
        body = (json.dumps(obj, indent=2) + "\n").encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _text(self, s: str, code: int = 200, extra: dict | None = None) -> None:
        body = s.encode()
        self.send_response(code)
        self.send_header("Content-Type", "text/plain; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        for k, v in (extra or {}).items():
            self.send_header(k, v)
        self.end_headers()
        self.wfile.write(body)

    @staticmethod
    def _push_status() -> dict:
        """What the write path would do right now, and why not, if not. An
        operator should be able to answer 'is push on, and against WHAT plm?'
        without reading env vars off a container."""
        try:
            push.gate()
            reason = ""
        except push.Refused as exc:
            reason = str(exc).splitlines()[0]
        return {
            "enabled": config.ALLOW_PUSH and not reason,
            "allow_push_flag": config.ALLOW_PUSH,
            "writes_to": config.PUSH_PLM_URL,
            "target_is_sandbox": push.looks_like_sandbox(config.PUSH_PLM_URL),
            "allow_prod_flag": config.PUSH_ALLOW_PROD,
            "proposal_ref": config.PUSH_REF,
            "actors_configured": len(set(push.tokens().values())),
            "refused_because": reason or None,
        }

    def log_message(self, fmt, *args):  # one tidy line per request
        print(f"[{time.strftime('%H:%M:%S')}] {self.address_string()} {fmt % args}",
              flush=True)

    # ---- routing ---------------------------------------------------------
    def do_GET(self):
        self._dispatch()

    def do_POST(self):
        self._dispatch()

    def do_PUT(self):                  # stage 17: an LFS upload, and only that
        path = self.path.partition("?")[0]
        if not (self._direct and "/info/lfs/objects/" in path):
            return self._text("405 PUT is for LFS uploads only\n", 405)
        self._dispatch()

    # ---- direct-serve mode ----------------------------------------------
    # config.DIRECT_ROOT is set: the repos are already on disk, generated by
    # plm/split.py. Everything this module normally does first — resolve a
    # number against plm, mirror the vault, replay version folders into a
    # throw-away repo — is skipped, and the request goes straight to
    # git-http-backend. Read-only, always.

    @property
    def _direct(self) -> Path | None:
        return Path(config.DIRECT_ROOT) if config.DIRECT_ROOT else None

    def _direct_repos(self) -> list[str]:
        root = self._direct
        return sorted(p.stem for p in root.glob("*.git")) if root else []

    def _direct_index(self):
        repos = self._direct_repos()
        lines = ["plm-git — DIRECT SERVE (git-first POC)", "",
                 f"  repos root: {config.DIRECT_ROOT}",
                 f"  {len(repos)} bare repositories"
                 + ("" if config.GITFIRST_ALLOW_PUSH else ", read-only"), "",
                 f"  git clone --recurse-submodules "
                 f"http://<host>:{config.PORT}/git/<NUMBER>.git", "",
                 "Submodule URLs are RELATIVE (../<NUMBER>.git), so children",
                 "and catalog.git resolve from this same /git/ root.", ""]
        if config.GITFIRST_ALLOW_PUSH:
            lines += [
                "PUSH IS ON. A pushed commit IS the revision — plm indexes it,",
                "it does not re-author it.", "",
                "  git clone http://<host>:%d/git/<NUMBER>.git" % config.PORT,
                "  git switch -c draft/<topic>",
                "  $EDITOR <the part> plm.toml        # bump `version`",
                "  git commit -am 'what changed and why'",
                '  git -c http.extraHeader="Authorization: Bearer $PLM_TOKEN" \\',
                f"      push origin HEAD:{config.GITFIRST_DRAFT_PREFIX}/<topic>"
                "   # -> a DRAFT in plm",
                '  git -c http.extraHeader="Authorization: Bearer $PLM_TOKEN" \\',
                f"      push origin HEAD:{config.PUSH_REF}"
                "              # -> submitted for approval",
                "",
                "A human approving in plm moves `main` and writes the tag.", ""]
        lines += [f"  {n}" for n in repos[:60]]
        if len(repos) > 60:
            lines.append(f"  … and {len(repos) - 60} more")
        lines.append("")
        return self._text("\n".join(lines))

    def _dispatch(self):
        path, _, query = self.path.partition("?")
        # Behind an edge the service is only reachable UNDER its clone root
        # (`location /git/` -> here), so liveness answers there too: plm's
        # address check probes `<clone base>/healthz`.
        if path == "/git/healthz":
            path = "/healthz"
        if self._direct:
            try:
                if path == "/":
                    return self._direct_index()
                if path == "/healthz":
                    return self._json({
                        "ok": True, "mode": "direct",
                        "root": config.DIRECT_ROOT,
                        "repos": len(self._direct_repos()),
                        "push": {
                            "enabled": bool(config.GITFIRST_ALLOW_PUSH
                                            and push.tokens()
                                            and config.GITFIRST_INDEX_TOKEN),
                            "indexes_to": config.GITFIRST_PLM_URL,
                            "draft_prefix": config.GITFIRST_DRAFT_PREFIX,
                            "propose_ref": config.PUSH_REF,
                            # ⛔ L3 — THE ACTOR LIST IS GONE. `/healthz` is
                            # anonymous and returned every plm username that
                            # holds a push token, which is a list of accounts to
                            # go and look for. A COUNT answers the operator's
                            # real question ("is push configured?") and names
                            # nobody.
                            "actors_configured": len(set(push.tokens().values())),
                        }})
                if path == "/api/parts":
                    return self._json([
                        {"number": n, "clone_url": f"/git/{n}.git"}
                        for n in self._direct_repos()])
                if path.startswith("/git/"):
                    return self._git_direct(path[len("/git"):], query)
                return self._text("not found\n", 404)
            except Exception as e:  # noqa: BLE001
                # ⛔ L3 — the class name, not the message. `f"500 {type(e).__name__}: {e}"`
                # hands the client filesystem paths and whatever else an
                # exception happens to carry; the message goes to the log, where
                # an operator can read it, and the client gets a reference.
                ref = f"{int(time.time() * 1000) % 100000:05d}"
                self.log_message("500 [%s] %s: %s", ref, type(e).__name__, e)
                return self._text(
                    f"500 plm-git hit a {type(e).__name__} handling this "
                    f"request (ref {ref}).\nThe reason is in the service log.\n",
                    500)
        try:
            if path == "/":
                return self._index()
            if path == "/healthz":
                return self._json({
                    "ok": True, "vault": str(config.VAULT),
                    "mirror": str(config.MIRROR),
                    "mirror_present": (config.MIRROR / "HEAD").exists(),
                    "repos": sorted(p.name for p in config.REPOS.glob("*.git"))
                    if config.REPOS.exists() else [],
                    "plm_url": config.PLM_URL,
                    "push": self._push_status(),
                })
            if path == "/api/parts":
                return self._json(list_parts())
            if path.startswith("/api/parts/"):
                rest = path[len("/api/parts/"):]
                num, _, action = rest.partition("/")
                num = urllib.parse.unquote(num)
                if action == "refresh":
                    if self.command != "POST":
                        return self._json({"error": "POST required"}, 405)
                    return self._json(ensure_fresh(num, force=True))
                if action:
                    return self._json({"error": "unknown action"}, 404)
                item = resolve(num)
                m = extract.ensure_mirror(refresh=True)
                stale, cached, cur = extract.is_stale(item, m)
                return self._json({
                    "number": item.number, "name": item.name,
                    "folder": item.folder, "former_numbers": item.former_numbers,
                    "resolver": item.source, "stale": stale,
                    "cached_folder_head": cached, "vault_folder_head": cur,
                    "clone_url": f"/git/{item.number}.git",
                    "proposals": push.ledger(item.number),
                    "stamp": extract.read_stamp(item.number),
                })
            if path.startswith("/git/"):
                return self._git(path[len("/git"):], query)
            return self._text("not found\n", 404)
        except NotFound as e:
            return self._text(f"404 unknown part: {e}\n", 404)
        except Exception as e:  # noqa: BLE001 — see the direct-mode handler
            ref = f"{int(time.time() * 1000) % 100000:05d}"
            self.log_message("500 [%s] %s: %s", ref, type(e).__name__, e)
            return self._text(
                f"500 plm-git hit a {type(e).__name__} handling this request "
                f"(ref {ref}).\nThe reason is in the service log.\n", 500)

    def _index(self):
        lines = ["plm-git — clone a part.", "",
                 f"  git clone http://<host>:{config.PORT}/git/<NUMBER>.git", "",
                 "cached repos:"]
        if config.REPOS.exists():
            for p in sorted(config.REPOS.glob("*.git")):
                st = extract.read_stamp(p.stem)
                lines.append(f"  {p.stem:<16} {st.get('commits','?'):>3} commits  "
                             f"{st.get('name','')}")
        lines += ["", "any item number with a vault folder works — the repo is",
                  "generated on first clone. GET /api/parts for the list.", ""]
        st = self._push_status()
        if st["enabled"]:
            lines += [
                f"push: ENABLED — proposals go to {st['writes_to']}"
                + ("  (SANDBOX)" if st["target_is_sandbox"] else "  (!! NOT a sandbox)"),
                "",
                "  git clone http://<host>:%d/git/<NUMBER>.git" % config.PORT,
                "  # edit, add a versions/v<next>/ folder, commit, then:",
                '  git -c http.extraHeader="Authorization: Bearer $PLM_TOKEN" \\',
                f"      push origin HEAD:{st['proposal_ref']}",
                "",
                "  a push is a PROPOSAL: it lands as a DRAFT revision plus a submitted",
                "  approval. A human approving in plm is the merge.", ""]
        else:
            lines += [f"push: disabled — {st['refused_because']}", ""]
        return self._text("\n".join(lines))

    # ---- the git bridge --------------------------------------------------
    def _git(self, path_info: str, query: str):
        """path_info looks like /KML-PRT-1009.git/info/refs"""
        pushing = is_push(path_info, query)
        actor = None
        if pushing:
            # THE DOOR. Both requests of a push (the ref advertisement and the
            # pack POST) come through here, and both are authenticated: a service
            # that authenticated only the POST would advertise a private part's
            # refs to anyone who asked to push.
            try:
                push.gate()
                actor = push.identify(
                    push.bearer_of(dict(self.headers.items())), push.plm_client())
            except push.Refused as exc:
                needs_creds = exc.needs_credential
                code = 401 if needs_creds else 403
                self.log_message("push refused (%s): %s", code,
                                 str(exc).splitlines()[0])
                # WWW-Authenticate on a 401 is not decoration: without it git
                # cannot tell which scheme to use, so a credential helper never
                # runs and the client sits there. With it, `credential.helper`
                # and `git push https://user:$TOKEN@host/...` both work, and a
                # client with no credential fails immediately instead of hanging.
                # ASCII only: HTTP header values are latin-1 on the wire, and an
                # em dash here raised mid-response — status line already sent,
                # then a second 500 response. Malformed reply, and the client
                # reported "weird server reply" instead of the refusal.
                extra = {"WWW-Authenticate":
                         'Basic realm="plm-git push (password = your plm token)"'} \
                    if needs_creds else {}
                return self._text(
                    f"{code} plm-git refused this push\n"
                    + "-" * 68 + "\n" + str(exc) + "\n" + "-" * 68 + "\n",
                    code, extra)

        parts = [p for p in path_info.split("/") if p]
        if not parts or not parts[0].endswith(".git"):
            return self._text("404 expected /git/<NUMBER>.git/...\n", 404)
        number = urllib.parse.unquote(parts[0][:-4])

        # Freshness is checked exactly where it matters: the ref advertisement.
        if len(parts) >= 2 and parts[1] == "info" and path_info.endswith("info/refs"):
            info = ensure_fresh(number)
            self.log_message("refresh %s -> %s", number, info.get("action"))
        elif not extract.repo_path(number).exists():
            ensure_fresh(number)

        return self._backend(path_info, query, config.REPOS, actor)

    def _git_direct(self, path_info: str, query: str):
        """Serve a pre-generated bare repo. No resolve, no extract, no replay.

        THE DOOR (stage 3). Reads are anonymous; a push is not. Both requests of
        a push — the ref advertisement AND the pack POST — are authenticated
        here, because a service that authenticated only the POST would advertise
        a private part's refs to anyone who asked to push.
        """
        # stage 17: the Git LFS API (`<repo>/info/lfs/...`) — git-lfs derives
        # it from the clone URL, so nothing needs configuring client-side.
        # Answered HERE, not by http-backend, and behind the same door: reads
        # anonymous, writes identified exactly as a push is.
        lparts = [p for p in path_info.split("/") if p]
        if len(lparts) >= 3 and lparts[1:3] == ["info", "lfs"]:
            if not re.match(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,64}\.git$", lparts[0]) \
                    or ".." in lparts[0] \
                    or not (Path(config.DIRECT_ROOT) / lparts[0] / "HEAD").exists():
                return self._text("404 no such repository\n", 404)
            return lfs.handle(self, lparts[0], "/".join(lparts[3:]),
                              self._direct_actor)
        pushing = is_push(path_info, query)
        actor = None
        if pushing:
            try:
                actor = self._direct_actor()
            except push.Refused as exc:
                code = 401 if exc.needs_credential else 403
                self.log_message("push refused (%s): %s", code,
                                 str(exc).splitlines()[0])
                # WWW-Authenticate on a 401 is not decoration: without it git
                # cannot tell which scheme to use, so a credential helper never
                # runs and the client just sits there. ASCII only — header
                # values are latin-1 on the wire and an em dash here raised
                # mid-response, after the status line had already been sent.
                extra = {"WWW-Authenticate":
                         'Basic realm="plm push (password = your plm token)"'} \
                    if exc.needs_credential else {}
                return self._text(
                    f"{code} plm refused this push\n" + "-" * 68 + "\n"
                    + str(exc) + "\n" + "-" * 68 + "\n", code, extra)
        return self._git_direct_serve(path_info, query, pushing, actor)

    def _direct_actor(self):
        """THE DOOR for a write in direct mode — a push or an LFS upload.
        Raises push.Refused (needs_credential decides 401 vs 403)."""
        if not config.GITFIRST_ALLOW_PUSH:
            raise push.Refused(
                "this plm-git is serving generated repos READ-ONLY.\n"
                "\n"
                "  to enable the write path:  "
                "PLMGIT_GITFIRST_ALLOW_PUSH=1\n"
                "  plus a token map (PLMGIT_PUSH_TOKENS_FILE) and the "
                "index token\n"
                "  (PLMGIT_GITFIRST_INDEX_TOKEN_FILE) — see "
                "plm-git/docs/AGENT-INSTRUCTIONS.md.")
        if not push.tokens():
            raise push.Refused(
                "push is enabled but no tokens are configured, so no "
                "push could ever be\nattributed to a plm actor — and an "
                "unattributable revision is worse than a\nrefused one.\n"
                "\n"
                "  PLMGIT_PUSH_TOKENS_FILE=<file of "
                "`<token>=<plm username>` lines>")
        return push.identify(
            push.bearer_of(dict(self.headers.items())),
            Plm(config.GITFIRST_PLM_URL))

    def _git_direct_serve(self, path_info: str, query: str, pushing: bool,
                          actor):
        parts = [p for p in path_info.split("/") if p]
        if not parts or not parts[0].endswith(".git"):
            return self._text("404 expected /git/<NUMBER>.git/...\n", 404)
        # The repo name is a part number and nothing else — no traversal, no
        # absolute path, no dot segments reaching out of the served root.
        if not re.match(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,64}\.git$", parts[0]) \
                or ".." in parts[0]:
            return self._text("404 not a repository name\n", 404)
        root = Path(config.DIRECT_ROOT)
        if not (root / parts[0] / "HEAD").exists():
            # A renumbered item left its old name behind as a redirect
            # (ops.rename_repo). Answering 301 is what makes every clone
            # somebody already has keep working after `renumber_item` — the
            # transport half of items.former_numbers.
            moved = root / f"{parts[0]}.redirect"
            if moved.is_file():
                target = moved.read_text().strip()
                if re.match(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,64}\.git$", target):
                    rest = path_info[len("/" + parts[0]):]
                    where = f"/git/{target}{rest}" + (f"?{query}" if query else "")
                    self.log_message("redirect %s -> %s", parts[0], target)
                    return self._text(
                        f"301 {parts[0]} was renumbered to {target[:-4]}\n"
                        f"git follows this by itself; update your remote to "
                        f"{where}\n", 301, {"Location": where})
            return self._text(
                f"404 no repo {parts[0]} under {config.DIRECT_ROOT}\n", 404)
        if pushing:
            # Written lazily, here, because this is the one moment we know the
            # repo is about to be pushed to — and it keeps plm/split.py able to
            # generate repos without knowing the write path exists.
            gitfirst.ensure_hooks(root / parts[0])
        return self._backend(path_info, query, root, actor)


    def _backend(self, path_info: str, query: str, project_root, actor):
        env = {
            "GIT_PROJECT_ROOT": str(project_root),
            "GIT_HTTP_EXPORT_ALL": "1",
            "PATH_INFO": path_info,
            "QUERY_STRING": query,
            "REQUEST_METHOD": self.command,
            "SCRIPT_NAME": "/git",
            "REMOTE_ADDR": self.client_address[0],
            # ⛔ M2 — REMOTE_USER IS THE RESOLVED ACTOR OR IT IS EMPTY. It used
            # to fall back to the client header `X-Plm-Actor` whenever `actor`
            # was None — i.e. on every request the (escapable, see M1) `pushing`
            # boolean did not catch — and BOTH hook modules accept REMOTE_USER
            # as an identity. Three comments in this file asserted that the
            # hooks "trust nothing else" and never see the client's header. They
            # did. The fallback is deleted; a request with no verified actor now
            # carries no actor, and `gitfirst.pre_receive` refuses it by name.
            "REMOTE_USER": (actor.name if actor else ""),
            "SERVER_PROTOCOL": "HTTP/1.1",
            "GIT_COMMITTER_NAME": "plm-git",
            "GIT_COMMITTER_EMAIL": config.COMMITTER_EMAIL,
            "HOME": os.environ.get("HOME", "/tmp"),
            "PATH": os.environ.get("PATH", "/usr/bin:/bin"),
        }
        if ct := self.headers.get("Content-Type"):
            env["CONTENT_TYPE"] = ct
        if enc := self.headers.get("Content-Encoding"):
            env["HTTP_CONTENT_ENCODING"] = enc
        # Modern git clients negotiate protocol v2 through this header; drop it
        # and every clone silently downgrades to v0.
        if gp := self.headers.get("Git-Protocol"):
            env["GIT_PROTOCOL"] = gp
        if actor:
            env.update({"PLMGIT_ACTOR": actor.name,
                        "PLMGIT_ACTOR_KIND": actor.kind,
                        "PLMGIT_ACTOR_ROLES": ",".join(actor.roles),
                        "PLMGIT_ACTOR_VIA": actor.via})
        # The hooks are plm_git modules; they need the package importable and the
        # same configuration this process is running with.
        # The hooks are plm_git modules AND they import plm.gitvalidate (one
        # code path for "is this a legal revision?"), so both roots are needed.
        env["PYTHONPATH"] = os.pathsep.join(
            [str(extract.APP_DIR), str(Path(extract.APP_DIR).parent)])
        # ⛔ H3 — AN EXPLICIT ALLOWLIST, NOT A PREFIX WILDCARD. This used to
        # copy every `PLM_*` / `PLMGIT_*` / `GIT_CONFIG_*` variable into the
        # `git http-backend` CGI environment, "because plm.gitvalidate has to
        # find the OTHER repos (PLM_REPOS)" — which is ONE variable's worth of
        # need met with a wildcard, and the effect was that the prod filedrop
        # bearer was inherited by `git-upload-pack`, `git-receive-pack` and
        # every hook child, in the container most exposed to untrusted input.
        #
        # The hooks read exactly these. Adding one is a line here, which is the
        # point: an env variable that reaches a receive-pack child should be a
        # decision somebody made.
        for k, v in os.environ.items():
            if k in _ENV_PASSTHROUGH and k not in env:
                env[k] = v
            # GIT_CONFIG_COUNT/KEY_n/VALUE_n is how the operator configures the
            # served repos (uploadpack.allowFilter, receive.fsckObjects) without
            # writing a line into every generated repo. It is a config mechanism,
            # not a credential, and a client header cannot set it.
            elif k.startswith("GIT_CONFIG_") and k not in env:
                env[k] = v

        # Request body -> a temp file used as the child's stdin. Deadlock-free
        # (no concurrent write/read on pipes) and it lets us stream the big side,
        # the packfile, straight back to the client.
        # ⛔ H5 — REFUSE AN OVERSIZED BODY BEFORE READING A BYTE. This spooled
        # the request body to a temp file using the client's own
        # `Content-Length` with no cap at all, BEFORE spawning http-backend and
        # (for upload-pack) with no authentication in front of it — an anonymous
        # disk-fill against the container's writable layer, which is the host
        # root filesystem and not the POC's own volume.
        n = int(self.headers.get("Content-Length") or 0)
        if n > MAX_BODY:
            self.log_message("body too large: %d > %d", n, MAX_BODY)
            return self._text(
                f"413 this request body is {n:,} bytes; the limit is "
                f"{MAX_BODY:,}.\n"
                "A push larger than this is a push that should be several "
                "(PLMGIT_MAX_BODY).\n", 413)
        with tempfile.TemporaryFile() as body:
            if n:
                remaining = n
                while remaining > 0:
                    chunk = self.rfile.read(min(65536, remaining))
                    if not chunk:
                        break
                    body.write(chunk)
                    remaining -= len(chunk)
                    # A lying Content-Length cannot outrun the cap either: the
                    # loop is bounded by `n`, which was already checked, and
                    # `read()` returning short ends it.
            body.seek(0)
            env["CONTENT_LENGTH"] = str(n)
            proc = subprocess.Popen([config.GIT, "http-backend"], env=env,
                                    stdin=body, stdout=subprocess.PIPE,
                                    stderr=subprocess.PIPE)
            self._relay(proc)

    def _relay(self, proc: subprocess.Popen):
        """Parse the CGI response headers, then stream the body chunked."""
        headers, status = [], 200
        buf = b""
        while b"\r\n\r\n" not in buf and b"\n\n" not in buf:
            chunk = proc.stdout.read(1)
            if not chunk:
                break
            buf += chunk
        head, _, leftover = buf.partition(b"\n\n")
        head = head.replace(b"\r\n", b"\n")
        for line in head.split(b"\n"):
            if not line.strip():
                continue
            k, _, v = line.decode(errors="replace").partition(":")
            v = v.strip()
            if k.lower() == "status":
                status = int(v.split()[0])
            else:
                headers.append((k, v))
        self.send_response(status)
        for k, v in headers:
            self.send_header(k, v)
        self.send_header("Transfer-Encoding", "chunked")
        self.end_headers()

        def emit(data: bytes):
            self.wfile.write(b"%x\r\n" % len(data) + data + b"\r\n")

        try:
            if leftover:
                emit(leftover)
            while True:
                chunk = proc.stdout.read(65536)
                if not chunk:
                    break
                emit(chunk)
            self.wfile.write(b"0\r\n\r\n")
        except BrokenPipeError:
            pass
        finally:
            err = proc.stderr.read()
            proc.wait()
            if err.strip():
                self.log_message("http-backend stderr: %s",
                                 err.decode(errors="replace").strip()[:400])


def main() -> None:
    if config.DIRECT_ROOT:
        root = Path(config.DIRECT_ROOT)
        n = len(list(root.glob("*.git"))) if root.is_dir() else 0
        print(f"plm-git: DIRECT SERVE root={config.DIRECT_ROOT} "
              f"repos={n} (read-only; no vault, no extract, no replay)",
              flush=True)
        srv = ThreadingHTTPServer((config.BIND, config.PORT), Handler)
        srv.daemon_threads = True
        print(f"plm-git listening on {config.BIND}:{config.PORT}", flush=True)
        return srv.serve_forever()
    config.REPOS.mkdir(parents=True, exist_ok=True)
    print(f"plm-git: vault={config.VAULT} cache={config.CACHE} "
          f"plm={config.PLM_URL}", flush=True)
    try:
        push.gate()
        print(f"plm-git: PUSH ENABLED — proposals -> {config.PUSH_PLM_URL} "
              f"({'sandbox' if push.looks_like_sandbox(config.PUSH_PLM_URL) else 'PROD'}), "
              f"ref {config.PUSH_REF}, actors "
              f"{sorted(set(push.tokens().values()))}", flush=True)
    except push.Refused as exc:
        print(f"plm-git: push OFF — {str(exc).splitlines()[0]}", flush=True)
    srv = ThreadingHTTPServer((config.BIND, config.PORT), Handler)
    srv.daemon_threads = True
    print(f"plm-git listening on {config.BIND}:{config.PORT}", flush=True)
    srv.serve_forever()


if __name__ == "__main__":
    main()
