    "== ONE PIECE OF WORK = ONE PULL REQUEST. OPEN IT, PUSH INTO IT, SUBMIT IT, "
    "THEN WAIT — A HUMAN APPROVES ==\n"
    "The owner's words: \"the agent is asking me to approve a pull request to "
    "main for the project — and then also approve a release.\" So:\n"
    "  A PULL REQUEST (#n; CHG-n is its legacy label, accepted everywhere) "
    "is every proposal (draft branch) "
    "a piece of work touches, across however many repos — the part, the "
    "assembly's pin bump, the coupon that proves the fit — reviewed and "
    "decided ONCE. The approver gets one link and one page.\n"
    "  1. OPEN IT on the first push, natively:\n"
    "       git push -o pr=new -o title=\"Raise ring pillars 1 mm\" "
    "origin HEAD:draft/v0.5.0\n"
    "     The `remote:` output names it: `plm: pull request #12 (CHG-12, …)`. (Or "
    "open_change(title, body, project) first.) It also names the REVIEW "
    "BASELINE — the release tag or open draft your commit descends from "
    "(`plm: baseline 0c38698de4 (draft/v0.1.0, inferred)`) — and the "
    "`compare:` line is that baseline...your head. Branched from somewhere "
    "else on purpose? `-o base=<ref|sha>` names it (an ancestor of the "
    "head).\n"
    "  2. PUSH INTO IT — every other repo the work touches:\n"
    "       git push -o pr=12 origin HEAD:draft/v0.9.0\n"
    "     (or add_to_change('CHG-12', number=…, ref='draft/…') for a draft "
    "plm made). In an assembly, pin the child at the child's DRAFT HEAD "
    "(`git -C parts/<CHILD> checkout <its draft sha>`): at merge plm "
    "re-pins it to the child's new release tag, in the parent's release "
    "commit, and says so. Pinning an OLDER draft commit of a member is "
    "refused at decision time — re-pin to its head.\n"
    "  3. SUBMIT IT: submit_change('CHG-12', note=…). Every member goes into "
    "review, impact analysis runs (which parents pin what you changed and "
    "are NOT in the pull request — `impact` in get_change), and ONE "
    "`review.requested` goes to the approver with the page link.\n"
    "  4. DRAFT DISPOSITIONS for the parents you did not bump: "
    "draft_dispositions('CHG-12') proposes `bump` / `use_as_is` / "
    "`no_impact` with the facts as the reason; a human confirms. Not a gate "
    "at PROTOTYPE; required (human-confirmed) when a member targets "
    "RELEASED. `bump` means the pin bump is IN this pull request — push it. "
    "`impact_coverage` says which where-used parents were looked at and how "
    "(an empty impact is not \"unchecked\"). Items carrying a DIFFERENT copy "
    "of a source a member carries are listed as `source-drift` — advisory, "
    "never a gate: give each a reason (`historical`, or "
    "`unchanged_geometry` — draft_dispositions(render=true) renders the "
    "item's own selector against both copies and drafts it when identical), "
    "or move the source to one `lib/<N>` home (the shared-source check "
    "prints the lines).\n"
    "  5. WAIT. Do not decide it, do not poll-and-resubmit. A REJECTION "
    "comes with threads: fix, push to the same branches (the push dismisses "
    "the stale signoff), submit_change again. A push to a member WHILE it is "
    "in review takes the pull request out of review (the signoff no longer covers "
    "those bytes) — the push output says so; submit again when whole.\n"
    "  Approval is ONE decision: plm pre-flights every member (mergeable, "
    "checks, policy, threads, dispositions) BEFORE the first merge — a "
    "refusal merges nothing and names the member and the fix — then merges "
    "children before parents. A proposal that is one of several in a pull request "
    "cannot be decided on its own. A lone proposal you submit is wrapped in "
    "a pull request of one: every review is a pull request.\n"
    "  \"Just build it\" is a per-project SETTING (approval_policy() says "
    "`auto`): there a whole pull request merges by policy, stamped AUTO, in the "
    "same order with the same pre-flight. It is not the default.\n"
    "A RELEASE asks *is this revision ready to build against?* It acts on an "
    "EXISTING tag, changes no files, mints no version, and is always a "
    "decision. request_release(number, version) on an ASSEMBLY computes its "
    "UNRELEASED CLOSURE (every descendant pin not RELEASED) and proposes ONE "
    "RELEASE SET: a workflow per member (checklist, checks, evidence), "
    "ordered bottom-up, a passing coupon attesting the fit line BY "
    "REFERENCE where one exists, ONE human decision that promotes the "
    "whole set. A member pinned at an unreleased COMMIT (not a tag) blocks "
    "the set and the page names the pull request that must merge first. Attest "
    "the lines you can PROVE; the human attests the rest and decides. **Do "
    "not revise a part in order to release it.** Promoting is what that is "
    "for.\n"
