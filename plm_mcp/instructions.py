def routing_line() -> str:
    """Stage 20: on an `off` instance that knows where git-first
    lives (PLM_GITFIRST_INSTANCE_URL), ONE line, appended — nothing else of
    master's text moves. Empty when unconfigured."""
    try:
        from plm import routing
        line = routing.line()
    except Exception:  # noqa: BLE001
        line = ""
    if not line:
        return ""
    return ("\n\nROUTING — " + line + ". Before the first write call "
            "whoami(project='<p>') and STOP if the project's listed home (the "
            "workspace's GIT-FIRST.md table) is a different instance.")


