#: The explode gate as a `write` project meets it (stage 15): against the base.
def _issues_advice() -> str:
    """Where an agent reports a gap, from the operator (PLM_ISSUES_ADVICE, or
    PLM_ISSUES_ADVICE_FILE for a longer text). Empty = the generic sentence:
    plm itself has no idea which tracker its operator uses."""
    path = os.environ.get("PLM_ISSUES_ADVICE_FILE", "").strip()
    if path:
        try:
            text = open(path, encoding="utf-8").read().strip()
            if text:
                return text
        except OSError:
            pass
    return (os.environ.get("PLM_ISSUES_ADVICE", "").strip()
            or "Missing capability, bug, awkward workflow → file an issue with "
               "the operator of this plm instance: title 'plm: <what>', "
               "include tool/endpoint, expected vs actual. Do NOT silently "
               "work around gaps — the report IS the contribution.")


