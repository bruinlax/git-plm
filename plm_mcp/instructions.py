    "approving is a REAL decision and the record says a bot made it — so say "
    "why in the note. When it does not, the refusal names the setting; that "
    "is information for the human, not a thing to route around.\n"
    "You may ALWAYS attest checklist lines you can prove, and should: "
    "`sign_release(id, kind='checklist', item=<the line>, note=<your "
