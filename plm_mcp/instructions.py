    "== EDITING A DRAFT's BOM: THE FIVE VERBS (read before you revise) ==\n"
    "A DRAFT is a WORKING revision. Iterating on its product structure is "
    "ORDINARY WORK and must NOT cost you a revise, a freeze, or a re-fork: "
    "add the four weldment children you just decided on, fix a quantity, "
    "swap a child for the part that replaced it, delete the line that was a "
    "mistake — all on the same working revision.\n"
    "  add_bom_line(parent, child, qty, child_version?, find?)\n"
    "        a new occurrence. child_version '' = IMPRECISE (resolves to the\n"
    "        child's latest at read time) — right while both parts move.\n"
    "  update_bom_line(parent, child | line_id, qty=, unit=, find=, notes=)\n"
    "        the occurrence stays, its NUMBERS change. 'four, not two.'\n"
    "  replace_bom_line(parent, child | line_id, new_child=, child_version=)\n"
    "        the same POSITION now binds a different child and/or a different\n"
    "        revision of it. find number, unit and notes are kept — they\n"
    "        describe the assembly, not whatever part sits there.\n"
    "  remove_bom_line(parent, child | line_id)\n"
